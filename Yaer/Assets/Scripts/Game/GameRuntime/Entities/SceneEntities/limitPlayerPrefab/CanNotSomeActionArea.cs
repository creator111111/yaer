using UnityEngine;

public enum DisableAcitonType { 
    None,
    SquatUp, // ?????????
    Jump, // ???
}

// ??????????????????????????????????????
public class CanNotSomeActionArea : MonoBehaviour
{
    public Collider2D colliderObj;
    public DisableAcitonType curDisableType;
    
    private PlayerLogic crawlingPlayer;
    private bool isCrawling;
    private bool didDisableOpenMenu;

    private PlayerLogic playerInArea;
    private bool isPlayerInArea;

    private bool hasEnteredClimbMove;
    private float crawlStartTime;
    private float exitGraceTime = 0.15f;

    // ?????????[???????? Exit/Enter???????????????????????????????
    private bool isPendingExit;
    private float pendingExitStartTime;
    private float exitJitterGraceTime = 0.35f;
    // Start is called before the first frame update
    void Start()
    {
        if (colliderObj == null)
        {
            colliderObj = GetComponent<Collider2D>();
        }
        
    }

    // Update is called once per frame
    void Update()
    {
        // ??????????????????????????????????????
        // ???????????? ClimbMoveState ????????????
        // ?????????????/??????????????????????? => ??????????
        if (isCrawling && crawlingPlayer != null && curDisableType == DisableAcitonType.SquatUp)
        {
            // ???? ClimbSM ???????????????????????????????????????
            if (!hasEnteredClimbMove)
            {
                var csAnimator = crawlingPlayer.componentSystem.GetComponent<PlayerCsAnimator>();
                // ????????????????????????ClimbMoveState??????????????????????
                if (csAnimator != null && csAnimator.GetSign("IsClimbMove"))
                {
                    hasEnteredClimbMove = true;
                }
            }

            // ??????????????????????????????????????????[?? => ?? Stop??
            if (isPendingExit && !isPlayerInArea && hasEnteredClimbMove)
            {
                if (Time.time - pendingExitStartTime >= exitJitterGraceTime)
                {
                    StopAutoCrawl(crawlingPlayer);
                }
            }

            // ???????????????????????????????????????????????????
            if (!hasEnteredClimbMove && (Time.time - crawlStartTime > 3f))
            {
                StopAutoCrawl(crawlingPlayer);
            }
        }

        // ???????????????????????????+??????????????????
        if (curDisableType != DisableAcitonType.SquatUp) { return; }
        if (!isPlayerInArea) { return; }
        if (playerInArea == null) { return; }
        if (isCrawling) { return; }

        if (!playerInArea.isDead && playerInArea.componentSystem != null)
        {
            var input = playerInArea.componentSystem.GetComponent<PlayerInputComponent>();
            // ?????????????? S ????????????
            if (input != null && input.HasSquatInput() && TryGetCrawlMoveDir(input, out _))
            {
                // StartAutoCrawl ????????????????
                StartAutoCrawl(playerInArea);
            }
        }
    }

    private void OnDisable()
    {
        // ???????????????/??????????????????????????
        if (isCrawling && crawlingPlayer != null)
        {
            StopAutoCrawl(crawlingPlayer);
        }

        isPlayerInArea = false;
        playerInArea = null;
    }

    private void OnTriggerEnter2D(Collider2D collider)
    {
        var enetityLogic = collider.GetComponent<ColliderResponder>()?.GetEntityLogic() as BaseEntityLogic;
        if (enetityLogic is PlayerLogic playerLogic)
        {
            playerInArea = playerLogic;
            isPlayerInArea = true;
            checkActionState(playerLogic, true);
        }
    }

    private void OnTriggerExit2D(Collider2D collider)
    {
        var enetityLogic = collider.GetComponent<ColliderResponder>()?.GetEntityLogic() as BaseEntityLogic;
        if (enetityLogic is PlayerLogic playerLogic)
        {
            if (playerInArea == playerLogic)
            {
                isPlayerInArea = false;
                playerInArea = null;
            }
            checkActionState(playerLogic, false);
        }
    }

    private void SetAllowOpenMenu(bool allow)
    {
        var sceneMgr = GameManager.GetGameSceneManager();
        if (sceneMgr == null) { return; }

        var inputMgr = sceneMgr.GetModule<InputComponentGSM>();
        inputMgr?.SetAllowOpenMenu(allow);
    }

    private bool TryGetCrawlMoveDir(PlayerInputComponent input, out PlayerInputComponent.AutoInputMove autoMove)
    {
        autoMove = PlayerInputComponent.AutoInputMove.None;
        if (input == null) { return false; }

        // ???????????????????????????? Left/Right
        // ????????? index=0/1 ????????????????????????????????
        for (int i = 0; i < 20; i++)
        {
            var cmd = input.GetPlayerCurInputCmd(i);
            if (cmd == ControlInputType.None)
            {
                // GetPlayerCurInputCmd ???? None ??????????????
                break;
            }

            if (cmd == ControlInputType.Left)
            {
                autoMove = PlayerInputComponent.AutoInputMove.Left;
                return true;
            }

            if (cmd == ControlInputType.Right)
            {
                autoMove = PlayerInputComponent.AutoInputMove.Right;
                return true;
            }
        }

        return false;
    }

    private void StartAutoCrawl(PlayerLogic playerLogic)
    {
        if (isCrawling) { return; }

        var input = playerLogic.componentSystem.GetComponent<PlayerInputComponent>();
        if (input == null) { return; }

        // ?????????????? S ????????????
        if (!input.HasSquatInput()) { return; }

        // TryGetCrawlMoveDir(input, out autoMove) ??????????????????????
        if (!TryGetCrawlMoveDir(input, out var autoMove) ||
            autoMove == PlayerInputComponent.AutoInputMove.None) { return; }

        isCrawling = true;
        crawlingPlayer = playerLogic;
        hasEnteredClimbMove = false;
        crawlStartTime = Time.time;
        didDisableOpenMenu = false;
        isPendingExit = false;
        pendingExitStartTime = 0;

        Debug.Log($"[CanNotSomeActionArea] StartAutoCrawl autoMove={autoMove} player={playerLogic.name}");

        // ??????/???ESC
        playerLogic.DisablePlayerMove(true);
        SetAllowOpenMenu(false);
        didDisableOpenMenu = true;

        // ?????????? AutoMoveState????????????
        // ?? SquatStayState ????????HasMoveInput??????????????? ClimbDownState -> ClimbMoveState
        input.AutoMoveState = autoMove;

        // ????????????????????????? ChangeStateToSquat???????????????????????????????
        var csAnimator = playerLogic.componentSystem.GetComponent<PlayerCsAnimator>();
        if (csAnimator != null && csAnimator.GetSign(PlayerStateSign.Squat) == false)
        {
            // ?????????????????????????????????????????? SquatSM
            playerLogic.ChangeStateToSquat();
        }
    }

    private void StopAutoCrawl(PlayerLogic playerLogic)
    {
        if (!isCrawling || crawlingPlayer != playerLogic) { return; }

        Debug.Log($"[CanNotSomeActionArea] StopAutoCrawl player={playerLogic.name}");
        isCrawling = false;
        crawlingPlayer = null;
        hasEnteredClimbMove = false;
        isPendingExit = false;
        pendingExitStartTime = 0;

        // ????????????/????????AutoMoveState ???????? Left/Right ??????????????????????????
        var input = playerLogic.componentSystem.GetComponent<PlayerInputComponent>();
        if (input != null)
        {
            input.AutoMoveState = PlayerInputComponent.AutoInputMove.None;
            input.SetAllowMove(false); // ??? curPlayerAllCmds
        }

        // ?????????ClimbMoveState ???? Exit ??? StopMove??????????????????
        playerLogic.componentSystem.GetComponent<PlayerMoveComponent>()?.StopMove();

        if (didDisableOpenMenu)
        {
            SetAllowOpenMenu(true);
            didDisableOpenMenu = false;
        }

        // ??????????????????????? SquatUpState/CombatIdleState??
        // ?????????????/?????????????????????? ClimbDown -> ClimbMove ???????????
        // ?????????????????????/??????
        playerLogic.isEnableSquatUp = true;
        playerLogic.DisablePlayerMove(false);
    }


    void checkActionState(PlayerLogic playerLogic, bool isEnterArea = true)
    {
        switch (curDisableType)
        {
            case DisableAcitonType.None:
                break;
            case DisableAcitonType.SquatUp:
                if (isEnterArea)
                {
                    // ?????????????????????
                    playerLogic.isEnableSquatUp = false;

                    // ?????????????+???????????????
                    StartAutoCrawl(playerLogic);
                    isPendingExit = false;
                    pendingExitStartTime = 0;
                }
                else
                {
                    // ?????????????????????
                    if (isCrawling && crawlingPlayer == playerLogic)
                    {
                        // ????????????????????????????????????????????????? ClimbMoveState??
                        // ???????????????????????????????
                        // ?????????????????? ClimbMoveState ??????????????
                        // ???????????????????/?????????????????????????????????????????????????
                        isPendingExit = true;
                        pendingExitStartTime = Time.time;
                    }
                    else
                    {
                        playerLogic.isEnableSquatUp = true;
                    }
                }
                break;
            case DisableAcitonType.Jump:
                playerLogic.isEnableJump = !isEnterArea;
                break;
            default:
                break;
        }
    }
}
